const assert=require('node:assert/strict');
const C=require('../campaign.js');
const R=require('../rules.js');
const clone=value=>JSON.parse(JSON.stringify(value));
const first=C.newCharacter(17,28,47,6,'Axe');
first.disciplines=['Camouflage','Hunting','Healing','Weaponskill','Mindshield'];
first.section=350;first.ep=19;first.notes='Remember Banedon';
first.csBonus=1;first.weapons.push('Sword');first.equipped=1;
first.special.push({name:'Crystal Star Pendant',effect:'Gift from Banedon',ep:0});
const before=clone(first);
const options={gold:15,discipline:'Mindblast',items:['Shield','Two Meals']};
const second=C.startBook2(first,options);
assert.deepEqual(first,before,'Starting Book 2 must never change the original chart');
for (const key of ['baseCS','baseEP','csBonus','epBonus','ep','mastery','weapons','equipped','backpack','notes']) assert.deepEqual(second[key],first[key],`Carry ${key}`);
assert.equal(second.gold,50);assert.equal(second.book,2);assert.equal(second.section,1);
assert.equal(second.disciplines.length,6);assert.equal(C.limit(second),6);assert.equal(second.meals,3);
assert.equal(second.special.filter(v=>v.name==='Seal of Hammerdal').length,1);
assert.equal(R.combatSkill(second).equipment,2);
const saved=C.validateSave({version:2,activeBook:2,books:{1:first,2:second}});
saved.books[2].weapons.pop();saved.books[2].disciplines.pop();
assert.deepEqual(saved.books[1].weapons,first.weapons,'Book charts are independent');
assert.equal(saved.books[1].disciplines.length,5);
const old=clone(first);delete old.book;delete old.continued;
const migrated=C.validateSave(old);
assert.equal(migrated.activeBook,1);assert.equal(migrated.books[1].section,350);assert.equal(migrated.books[1].ep,19);
assert.equal(C.validateSave(second).activeBook,2);
assert.deepEqual(C.validateSave(C.validateSave(old)),C.validateSave(old),'Save format survives a round trip');
assert.throws(()=>C.startBook2(first,{...options,discipline:'Healing'}),/new Kai/);
assert.throws(()=>C.startBook2({...first,ep:0},options),/Complete Book 1/);
assert.throws(()=>C.startBook2({...first,disciplines:[]},options),/five Kai/);
assert.throws(()=>C.startBook2({...first,combat:{name:'Enemy',cs:10,ep:10,maxEP:10,modifier:0,immune:false,rounds:[],status:'active'}},options),/finish any combat/);
assert.throws(()=>C.startBook2(first,{...options,items:['Spear']}),/two weapons/);
const exchanged=C.startBook2(first,{...options,keepWeapons:[0],items:['Spear','Shield']});
assert.deepEqual(exchanged.weapons,['Axe','Spear']);assert.equal(exchanged.equipped,-1);
const full={...first,meals:7,backpack:['Healing Potion']};
assert.throws(()=>C.startBook2(full,options),/backpack is full/);
assert.equal(C.startBook2(full,{...options,items:['Shield']}).backpack.length,1);
assert.throws(()=>C.startBook2(first,{...options,items:['Shield','Shield']}),/different/);
assert.throws(()=>C.validateSave({...second,continued:false}),/valid Book/);
assert.throws(()=>C.validateSave({...second,equipped:-2}),/valid Book/);
assert.throws(()=>C.validateSave({version:2,activeBook:2,books:{1:first}}),/missing/);
assert.throws(()=>C.validateSave({version:2,activeBook:1,books:{1:second}}),/do not match/);
const fresh=C.startBook2(null,{cs:16,ep:24,gold:12,mastery:'Sword',items:['Sword','Chainmail Waistcoat']});
assert.equal(C.limit(fresh),5);assert.equal(fresh.ep,28);assert.equal(R.maxEndurance(fresh),28);
assert.deepEqual(fresh.weapons,['Sword']);assert.equal(fresh.equipped,0);assert.equal(fresh.meals,0);assert.deepEqual(fresh.backpack,[]);
assert.equal(fresh.gold,12);assert.equal(fresh.special.length,3);
assert.equal(C.startBook2(first,{...options,items:['Chainmail Waistcoat']}).ep,23,'Armour grants its new EP bonus without healing previous wounds');
console.log('Passed: legacy save migration, campaign round trips, independent charts, returning and fresh Book 2 setup, sixth Discipline, armoury exchanges, equipment limits, gold cap, and invalid-save rejection.');
